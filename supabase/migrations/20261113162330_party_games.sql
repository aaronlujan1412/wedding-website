-- Aaronpardy and Bride Quest: two party games served as static pages from
-- public/, talking to app/api/<game>/ through public/games/shim.js.
--
-- They came with a small Node server that kept everything in files: db.json
-- (Bride Quest's live state), content.json (edits saved from the in-page
-- editor) and history/. This is that, one row per game. The live state is a
-- single jsonb map of document path -> object, exactly as db.json was, because
-- the shim reads the whole thing on every poll and a row per document would
-- turn every poll into an aggregate.
--
-- RLS on with no policies, like guests: only the secret key gets in.

create table party_game_state (
  game text primary key check (game in ('aaronpardy', 'bride-quest')),
  -- Bumped on every write; the shim sends back the last one it saw and gets
  -- "unchanged" if nothing moved.
  version bigint not null default 0,
  docs jsonb not null default '{}'::jsonb,
  -- NULL until the groom first saves from the page: the template in public/
  -- holds the original.
  content jsonb,
  -- Epoch ms of the last content save. Every open page is polling this, and a
  -- change makes it reload, as the pages did on claude.ai.
  content_stamp bigint not null default 0,
  updated_at timestamptz not null default now()
);

insert into party_game_state (game) values ('aaronpardy'), ('bride-quest');

alter table party_game_state enable row level security;

-- Every content save keeps the one it replaced. Restoring an old version is
-- copying a row's content back into party_game_state.
create table party_game_content_history (
  id bigint generated by default as identity primary key,
  game text not null references party_game_state (game),
  content jsonb not null,
  saved_at timestamptz not null default now()
);

create index party_game_content_history_by_game on party_game_content_history (game, id desc);

alter table party_game_content_history enable row level security;

-- ---------------------------------------------------------------------------
-- Writes are functions so each one is a single statement on the row: two
-- phones writing at once can't both read version 7 and both write 8.
-- ---------------------------------------------------------------------------

-- Returns the new version, or NULL when the document is new and the game is
-- already at p_max_docs.
create function party_game_put_doc(p_game text, p_path text, p_data jsonb, p_max_docs int)
returns bigint
language plpgsql
set search_path = public
as $$
declare
  v_version bigint;
begin
  update party_game_state
     set docs = docs || jsonb_build_object(p_path, p_data),
         version = version + 1,
         updated_at = now()
   where game = p_game
     and (docs ? p_path or (select count(*) from jsonb_object_keys(docs)) < p_max_docs)
  returning version into v_version;
  return v_version;
end;
$$;

-- Deleting a document that isn't there is not a change, so it doesn't bump.
create function party_game_delete_doc(p_game text, p_path text)
returns bigint
language plpgsql
set search_path = public
as $$
declare
  v_version bigint;
begin
  update party_game_state
     set docs = docs - p_path,
         version = version + 1,
         updated_at = now()
   where game = p_game and docs ? p_path
  returning version into v_version;

  if v_version is null then
    select version into v_version from party_game_state where game = p_game;
  end if;
  return v_version;
end;
$$;

-- Saves the editor's content, keeps the previous version, prunes to p_keep.
create function party_game_save_content(p_game text, p_content jsonb, p_keep int)
returns bigint
language plpgsql
set search_path = public
as $$
declare
  v_stamp bigint;
begin
  insert into party_game_content_history (game, content)
  select game, content from party_game_state
   where game = p_game and content is not null;

  update party_game_state
     set content = p_content,
         -- Never equal to the last stamp, even two saves in one millisecond:
         -- an equal stamp is how a page decides not to reload.
         content_stamp = greatest((extract(epoch from clock_timestamp()) * 1000)::bigint, content_stamp + 1),
         updated_at = now()
   where game = p_game
  returning content_stamp into v_stamp;

  delete from party_game_content_history
   where game = p_game
     and id not in (
       select id from party_game_content_history
        where game = p_game
        order by id desc
        limit p_keep
     );

  return v_stamp;
end;
$$;

-- Supabase grants EXECUTE on new public functions to anon and authenticated.
revoke execute on function party_game_put_doc(text, text, jsonb, int) from public, anon, authenticated;
revoke execute on function party_game_delete_doc(text, text) from public, anon, authenticated;
revoke execute on function party_game_save_content(text, jsonb, int) from public, anon, authenticated;
grant execute on function party_game_put_doc(text, text, jsonb, int) to service_role;
grant execute on function party_game_delete_doc(text, text) to service_role;
grant execute on function party_game_save_content(text, jsonb, int) to service_role;
